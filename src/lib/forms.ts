import type { Checklist, Field } from "./types";

/* The ER paper forms, as checklists. Also written to supabase/migrations/0003_er_forms.sql. */

const created_at = "2026-11-01T00:00:00.000Z";

let n = 0;
const key = (label: string) =>
  label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .slice(0, 36) || `f${++n}`;

const head = (label_en: string, label_ar = ""): Field => ({ key: `h_${key(label_en)}`, label_en, label_ar, type: "heading", required: false });
const item = (label_en: string, qty = "", extra: Partial<Field> = {}): Field => ({
  key: key(label_en),
  label_en,
  label_ar: "",
  type: "check",
  required: true,
  ...(qty ? { qty } : {}),
  ...extra,
});
const count = (label_en: string, unit = ""): Field => ({ key: key(label_en), label_en, label_ar: "", type: "number", unit, min: null, max: null, required: true });
const text = (label_en: string, label_ar: string, required = true): Field => ({ key: key(label_en), label_en, label_ar, type: "text", required });
const yesno = (label_en: string, label_ar: string, extra: Partial<Field> = {}): Field => ({ key: key(label_en), label_en, label_ar, type: "yesno", required: true, ...extra });

const base = (o: Partial<Checklist> & Pick<Checklist, "id" | "title_en" | "title_ar" | "icon" | "color" | "fields" | "sort">): Checklist => ({
  department_id: "dep-er",
  range_note: "",
  footer_note: "Nursing Service Department · Emergency Department",
  orientation: "landscape",
  active: true,
  created_at,
  ...o,
});

